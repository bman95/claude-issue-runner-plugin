#!/usr/bin/env bash
#
# Install the issue-runner plugin's skills from the ISSUE_RUNNER_CONTEXT
# environment variable into a Claude Code skills directory, so /issue-runner,
# /issue-plan and /gh-issue work in ANY project — new or existing, local or on
# the web — with nothing checked into the repo and no marketplace install.
#
# The value is produced by pack-context.sh. This script is the decode+install
# half: it is idempotent (safe to run every session) and never aborts a session
# when the variable is unset (it just no-ops in --hook mode). Each packed skill
# REPLACES any same-named directory under the destination (clean per-skill
# install — no stale files from older packs); everything else in the
# destination is left untouched.
#
# Two ways to run it:
#   1. Manually, once per machine / environment:
#        scripts/context-env/bootstrap-context.sh
#   2. As a Claude Code SessionStart hook (see docs/portable-context.md); pass
#      --hook so it emits the SessionStart JSON with reloadSkills:true and stays
#      silent+successful when the variable is absent.
#
# Resolution order for the payload:
#   $ISSUE_RUNNER_CONTEXT           (the value itself), else
#   $ISSUE_RUNNER_CONTEXT_FILE      (a path to a file holding the value).
#
# Install target (first that applies):
#   --dest DIR, else $ISSUE_RUNNER_SKILLS_DIR, else $HOME/.claude/skills
# Installing into ~/.claude/skills exposes the skills as USER-LEVEL commands
# (/issue-runner, /issue-plan, /gh-issue) and satisfies issue-runner Step 0's
# own fallback lookup of gh-issue at $HOME/.claude/skills/gh-issue/SKILL.md.
#
# Dependency-free: bash + coreutils + tar + gzip + base64.
set -euo pipefail

VAR_NAME="${ISSUE_RUNNER_CONTEXT_VAR:-ISSUE_RUNNER_CONTEXT}"
DEST="${ISSUE_RUNNER_SKILLS_DIR:-$HOME/.claude/skills}"
hook_mode=0

usage() { sed -n '2,/^set -euo/p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//; /^set -euo/d'; }

while [ $# -gt 0 ]; do
  case "$1" in
    --hook) hook_mode=1 ;;
    --dest) DEST="${2:?--dest needs a path}"; shift ;;
    --var)  VAR_NAME="${2:?--var needs a name}"; shift ;;
    -h|--help) usage; exit 0 ;;
    *) printf 'unknown argument: %s\n' "$1" >&2; exit 2 ;;
  esac
  shift
done

# SessionStart-hook JSON: a note for the model + a skills reload so the freshly
# written commands are picked up without restarting the session.
emit_hook_json() {
  ctx="$1"; reload="${2:-}"
  # Minimal, dependency-free JSON string escaping. The content is generated by
  # this script (paths, a version, skill names), so escaping the characters
  # that can plausibly occur — backslash, quote, newline, tab, CR — suffices;
  # exotic control bytes would need jq/python, which we deliberately avoid.
  esc="${ctx//\\/\\\\}"; esc="${esc//\"/\\\"}"
  esc="${esc//$'\n'/\\n}"; esc="${esc//$'\t'/\\t}"; esc="${esc//$'\r'/\\r}"
  # reloadSkills (a documented SessionStart output field) makes Claude Code
  # re-scan skills dirs mid-session, so the just-written commands appear without
  # a restart. Only on a successful install — never on the error/no-op paths.
  if [ "$reload" = "reload" ]; then
    printf '{"hookSpecificOutput":{"hookEventName":"SessionStart","additionalContext":"%s","reloadSkills":true}}\n' "$esc"
  else
    printf '{"hookSpecificOutput":{"hookEventName":"SessionStart","additionalContext":"%s"}}\n' "$esc"
  fi
}

# Never break a session. An unset variable in --hook mode is a clean, silent
# no-op (the environment simply doesn't carry the plugin); any OTHER failure in
# --hook mode still exits 0 but surfaces the error to the model via
# additionalContext — a corrupt value should be reported, not swallowed.
noop() {
  [ "$hook_mode" -eq 1 ] || { printf 'bootstrap-context: %s\n' "$1" >&2; exit 1; }
  printf '{"hookSpecificOutput":{"hookEventName":"SessionStart"}}\n'
  exit 0
}
die() {
  printf 'bootstrap-context: %s\n' "$1" >&2
  [ "$hook_mode" -eq 1 ] || exit 1
  emit_hook_json "bootstrap-context.sh failed: $1"
  exit 0
}

case "$VAR_NAME" in
  ''|[0-9]*|*[!A-Za-z0-9_]*) die "invalid variable name: '$VAR_NAME'" ;;
esac

value="${!VAR_NAME:-}"
if [ -z "$value" ] && [ -n "${ISSUE_RUNNER_CONTEXT_FILE:-}" ] && [ -f "$ISSUE_RUNNER_CONTEXT_FILE" ]; then
  value="$(cat "$ISSUE_RUNNER_CONTEXT_FILE")"
fi
[ -n "$value" ] || noop "\$$VAR_NAME is unset (and no \$ISSUE_RUNNER_CONTEXT_FILE); run pack-context.sh first"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# GNU coreutils decodes with -d; the pre-Ventura macOS/BSD base64 only knows -D.
b64d='-d'
printf '' | base64 -d >/dev/null 2>&1 || b64d='-D'

# Extraction happens into an empty temp dir. GNU tar and bsdtar both refuse
# member names with `..` and strip leading `/` by default, and `|| die` catches
# their non-zero exit — but a payload is still validated per skill below before
# anything touches DEST.
printf '%s' "$value" | base64 "$b64d" 2>/dev/null | tar -xzf - -C "$tmp" 2>/dev/null \
  || die "could not decode \$$VAR_NAME (corrupt or truncated value?)"
[ -d "$tmp/skills" ] || die "decoded payload has no skills/ tree"

# Validate then install each skill: a plain directory (no symlinks anywhere —
# a link like `gh-issue -> /etc` would otherwise land in DEST), a safe name,
# and a SKILL.md inside. Same-named directories in DEST are replaced wholesale
# so files deleted upstream don't linger; unrelated DEST entries are untouched.
mkdir -p "$DEST"
installed=""
for dir in "$tmp"/skills/*/; do
  [ -d "$dir" ] || continue
  name="$(basename "$dir")"
  case "$name" in
    *[!A-Za-z0-9._-]*|.|..) die "unsafe skill name in payload: '$name'" ;;
  esac
  [ -L "${dir%/}" ] && die "skill '$name' is a symlink — refusing to install"
  [ -n "$(find "$dir" -type l 2>/dev/null | head -1)" ] \
    && die "skill '$name' contains symlinks — refusing to install"
  [ -f "$dir/SKILL.md" ] || die "skill '$name' has no SKILL.md (corrupt payload?)"
  rm -rf "${DEST:?}/$name"
  cp -R "${dir%/}" "$DEST/$name"
  installed="$installed$name "
done
installed="${installed% }"
[ -n "$installed" ] || die "payload's skills/ tree has no skill directories"

version="?"
[ -f "$tmp/.claude-plugin/plugin.json" ] && version="$(sed -nE \
  's/.*"version"[[:space:]]*:[[:space:]]*"([^"]+)".*/\1/p' \
  "$tmp/.claude-plugin/plugin.json" | head -1)"

note="issue-runner ${version} skills installed to ${DEST}: ${installed}. Available as /issue-runner, /issue-plan, /gh-issue."
if [ "$hook_mode" -eq 1 ]; then
  emit_hook_json "$note" reload
else
  printf '%s\n' "$note"
fi
